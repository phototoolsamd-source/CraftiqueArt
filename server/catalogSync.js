const fs = require('fs');
const path = require('path');
const xlsx = require('xlsx');
const db = require('./db');

class CatalogSyncService {
  constructor() {
    this.isScanning = false;
    this.watcher = null;
    this.debounceTimer = null;
    this.sourceDir = null;
  }

  getSourcePath() {
    const settings = db.getSettings();
    if (settings.catalog_source_path && fs.existsSync(settings.catalog_source_path)) {
      return settings.catalog_source_path;
    }
    const candidates = [
      '/Volumes/STUDIO/AKSHAR/AKSHAR 1TB/AKSHAR SALES/|| Craftique Products',
      '/Volumes/STUDIO/AKSHAR/AKSHAR 1TB/AKSHAR SALES/|| Products Catlog',
      path.join(__dirname, '..', 'catalog_source')
    ];
    for (const c of candidates) {
      if (fs.existsSync(c)) return c;
    }
    return candidates[0];
  }

  cleanFolderName(name) {
    return String(name || '').replace(/^\d+[\.\s_-]*/, '').trim();
  }

  parseProductDetailsTxt(filePath) {
    try {
      if (!fs.existsSync(filePath)) return null;
      const content = fs.readFileSync(filePath, 'utf8');

      // Extract Product Title
      const titleMatch = content.match(/PRODUCT TITLE:\s*([^\n\r=]+)/i);
      const title = titleMatch ? titleMatch[1].trim() : null;

      // Extract Details & Materials description
      let description = '';
      const descMatch = content.match(/PRODUCT DETAILS & MATERIALS:\s*[-=]*\s*([\s\S]+?)(?====|Generated by|$)/i);
      if (descMatch) {
        description = descMatch[1].trim();
      }

      // Detect primary material from description
      let material = 'Bespoke Substrate';
      const lower = (description + ' ' + (title || '')).toLowerCase();
      if (lower.includes('canvas')) material = 'Archival Artist Canvas';
      else if (lower.includes('acrylic')) material = 'Cast Acrylic Sheet';
      else if (lower.includes('wood') || lower.includes('wooden')) material = 'Handcrafted Natural Wood';
      else if (lower.includes('linen')) material = 'Premium Woven Linen';
      else if (lower.includes('cardstock') || lower.includes('gsm')) material = 'Heavyweight 400+ GSM Cardstock';
      else if (lower.includes('vinyl')) material = 'Waterproof Polymeric Vinyl';
      else if (lower.includes('paper')) material = 'Archival Fine Art Paper';
      else if (lower.includes('magnet')) material = 'Magnetic Substrate + Neodymium';

      return { title, description, material };
    } catch (err) {
      console.warn('[CatalogSync] Error parsing txt file:', filePath, err.message);
      return null;
    }
  }

  parseSizeFromFilename(filename) {
    const m = filename.match(/Size_([a-zA-Z0-9_]+)_[a-f0-9]{4}\.(?:jpg|jpeg|png|webp)/i);
    if (!m) return null;
    let s = m[1];
    s = s.replace(/__([^_]+)(?:__|_$)/g, ' ($1)');
    s = s.replace(/(\d+)_(\d+)/g, '$1.$2');
    s = s.replace(/_x_/gi, ' × ');
    s = s.replace(/_/g, ' ');
    s = s.replace(/\s+/g, ' ').trim();
    return s || null;
  }

  sortImages(filenames) {
    const rank = (name) => {
      const lower = name.toLowerCase();
      if (lower.includes('hero')) return 1;
      if (lower.includes('banner')) return 2;
      if (lower.includes('size')) return 3;
      if (lower.includes('usage')) return 4;
      if (lower.includes('details')) return 5;
      if (lower.includes('beforeafter')) return 6;
      return 10;
    };
    return [...filenames].sort((a, b) => rank(a) - rank(b));
  }

  parseExcelFile(filePath) {
    try {
      const workbook = xlsx.readFile(filePath);
      const sheetName = workbook.SheetNames[0];
      const worksheet = workbook.Sheets[sheetName];
      const rows = xlsx.utils.sheet_to_json(worksheet, { defval: '' });
      if (!rows || rows.length === 0) return null;

      const row = rows[0];
      const mapped = {};

      const columnAliases = {
        name: ['productname', 'name', 'title', 'itemname', 'listingtitle', 'producttitle'],
        sku: ['sku', 'productid', 'itemid', 'productcode', 'skucode'],
        category: ['category', 'productcategory', 'type', 'department'],
        subcategory: ['subcategory', 'subcat'],
        description: ['description', 'productdescription', 'details', 'about', 'desc'],
        material: ['material', 'papertype', 'fabric'],
        size: ['size', 'dimensions', 'dimension'],
        selling_price: ['price', 'sellingprice', 'offerprice', 'ourprice', 'finalprice', 'rate'],
        mrp: ['mrp', 'maximumretailprice', 'listprice', 'regularprice'],
        stock: ['stock', 'inventory', 'quantity', 'qty'],
        tags: ['tags', 'keywords', 'searchtags']
      };

      for (const [key, val] of Object.entries(row)) {
        const normKey = String(key || '').trim().toLowerCase().replace(/[^a-z0-9]/g, '');
        for (const [prop, aliases] of Object.entries(columnAliases)) {
          if (aliases.includes(normKey) && !mapped[prop]) {
            mapped[prop] = val;
          }
        }
      }
      return mapped;
    } catch {
      return null;
    }
  }

  buildImageUrl(relPathSegments) {
    return '/catalog-images/' + relPathSegments.map(s => encodeURIComponent(s)).join('/');
  }

  getDefaultPricing(category, name) {
    const text = (category + ' ' + name).toLowerCase();
    if (text.includes('canvas frame')) {
      return { base: 899, mrp: 1599, production: '2-3 business days' };
    }
    if (text.includes('canvas hanging') || text.includes('scroll')) {
      return { base: 699, mrp: 1299, production: '2-3 business days' };
    }
    if (text.includes('album') || text.includes('photobook')) {
      return { base: 1299, mrp: 2499, production: '3-4 business days' };
    }
    if (text.includes('shadow box') || text.includes('miniature')) {
      return { base: 649, mrp: 1199, production: '2-3 business days' };
    }
    if (text.includes('paper frame')) {
      return { base: 499, mrp: 899, production: '1-2 business days' };
    }
    if (text.includes('photo frame') || text.includes('wrap canvas')) {
      return { base: 799, mrp: 1499, production: '2-3 business days' };
    }
    if (text.includes('artwork frame') || text.includes('photo art')) {
      return { base: 849, mrp: 1599, production: '2-3 business days' };
    }
    if (text.includes('magnet')) {
      return { base: 349, mrp: 699, production: '1-2 business days' };
    }
    if (text.includes('insta') || text.includes('mini print')) {
      return { base: 299, mrp: 599, production: '1-2 business days' };
    }
    if (text.includes('birthday') || text.includes('party')) {
      return { base: 999, mrp: 1899, production: '2-3 business days' };
    }
    if (text.includes('sticker') || text.includes('decal')) {
      return { base: 199, mrp: 399, production: '1-2 business days' };
    }
    if (text.includes('label')) {
      return { base: 249, mrp: 499, production: '1-2 business days' };
    }
    if (text.includes('invitation')) {
      return { base: 499, mrp: 999, production: '2-3 business days' };
    }
    if (text.includes('business card')) {
      return { base: 399, mrp: 799, production: '1-2 business days' };
    }
    return { base: 750, mrp: 1499, production: '2-3 business days' };
  }

  discoverProducts(sourceDir) {
    const products = [];

    const scanDir = (currentPath, pathSegments) => {
      let entries;
      try {
        entries = fs.readdirSync(currentPath, { withFileTypes: true });
      } catch {
        return;
      }

      const imageFiles = entries
        .filter(e => !e.isDirectory() && /\.(jpg|jpeg|png|webp)$/i.test(e.name))
        .map(e => e.name);

      const txtFile = entries.find(e => !e.isDirectory() && /\.txt$/i.test(e.name));
      const excelFile = entries.find(e => !e.isDirectory() && /\.(xlsx|xls|csv)$/i.test(e.name));
      const subDirEntries = entries.filter(e => e.isDirectory() && !e.name.startsWith('.'));

      // If this directory has images or product details text, it is a Product!
      if (imageFiles.length > 0 || txtFile) {
        const sortedImages = this.sortImages(imageFiles);
        const imageUrls = sortedImages.map(img =>
          this.buildImageUrl([...pathSegments, img])
        );

        const txtDetails = txtFile
          ? this.parseProductDetailsTxt(path.join(currentPath, txtFile.name))
          : null;

        const excelDetails = excelFile
          ? this.parseExcelFile(path.join(currentPath, excelFile.name))
          : null;

        // Size options: extract from 02_*_Size_* image names
        const sizeImageNames = sortedImages.filter(img => /Size_/i.test(img));
        let sizeOptions = [];

        if (sizeImageNames.length > 0) {
          sizeOptions = sizeImageNames.map((img, idx) => {
            const parsedName = this.parseSizeFromFilename(img);
            return {
              name: parsedName || `Option ${idx + 1}`,
              price_adj: idx === 0 ? 0 : idx * 150,
              default: idx === 0
            };
          });
        }

        // Also check if any empty subdirectories represent size/style options
        for (const sd of subDirEntries) {
          const sdPath = path.join(currentPath, sd.name);
          try {
            const sdContents = fs.readdirSync(sdPath);
            const hasSubImages = sdContents.some(f => /\.(jpg|jpeg|png|webp|txt)$/i.test(f));
            if (!hasSubImages) {
              const cleanOptName = this.cleanFolderName(sd.name);
              if (!sizeOptions.some(o => o.name.toLowerCase() === cleanOptName.toLowerCase())) {
                sizeOptions.push({
                  name: cleanOptName,
                  price_adj: sizeOptions.length * 100,
                  default: sizeOptions.length === 0
                });
              }
            }
          } catch {}
        }

        // Always add Custom Size option
        sizeOptions.push({ name: "Custom Size / Specifications", price_adj: 0, is_custom: true });

        // Category & Subcategory calculation
        const topCatFolder = pathSegments[0] || 'Customized Products';
        const cleanCategory = this.cleanFolderName(topCatFolder);
        let cleanSubcategory = null;
        if (pathSegments.length > 1) {
          cleanSubcategory = this.cleanFolderName(pathSegments[pathSegments.length - 1]);
        }

        products.push({
          dirPath: currentPath,
          pathSegments: [...pathSegments],
          category: cleanCategory,
          subcategory: cleanSubcategory,
          images: imageUrls,
          txtDetails,
          excelDetails,
          sizeOptions
        });
      }

      // Recurse into subdirectories (if they might contain separate products)
      for (const sd of subDirEntries) {
        const nextPath = path.join(currentPath, sd.name);
        scanDir(nextPath, [...pathSegments, sd.name]);
      }
    };

    scanDir(sourceDir, []);
    return products;
  }

  async syncCatalog(customPath = null) {
    if (this.isScanning) {
      return { status: 'busy', message: 'Sync already in progress' };
    }
    this.isScanning = true;

    try {
      const sourceDir = customPath || this.getSourcePath();
      this.sourceDir = sourceDir;

      if (!fs.existsSync(sourceDir)) {
        const errorMsg = `Catalog directory not found: ${sourceDir}`;
        db.updateSettings({
          sync_status: {
            connected: false,
            last_sync: new Date().toISOString(),
            error: errorMsg
          }
        });
        return { success: false, connected: false, error: errorMsg };
      }

      console.log(`[CatalogSync] 🔍 Scanning source: ${sourceDir}`);

      // If sourceDir is the external hard drive, mirror to public/catalog-images with deletion support
      const localPublicCatalog = path.join(__dirname, '..', 'public', 'catalog-images');
      if (sourceDir !== localPublicCatalog && fs.existsSync(sourceDir)) {
        try {
          if (!fs.existsSync(localPublicCatalog)) fs.mkdirSync(localPublicCatalog, { recursive: true });
          require('child_process').execSync(`rsync -av --delete --exclude '.DS_Store' "${sourceDir}/" "${localPublicCatalog}/"`, { stdio: 'ignore' });
          console.log('[CatalogSync] 🔄 Mirrored source folder into public/catalog-images (add/remove in sync)');
        } catch (mirrorErr) {
          console.warn('[CatalogSync] Notice on mirror to public folder:', mirrorErr.message);
        }
      }

      const discovered = this.discoverProducts(sourceDir);
      console.log(`[CatalogSync] 📦 Discovered ${discovered.length} product nodes.`);

      let newCount = 0;
      let updatedCount = 0;
      let totalImages = 0;
      const syncedProductIds = new Set();

      for (const item of discovered) {
        if (!item.images || item.images.length === 0) continue;
        totalImages += item.images.length;

        // Generate clean, deterministic SKU
        const skuBase = item.pathSegments
          .map(s => this.cleanFolderName(s).replace(/[^a-zA-Z0-9]/g, '_'))
          .filter(Boolean)
          .join('_')
          .toUpperCase();
        const sku = skuBase || `CRQ_PROD_${Date.now()}`;
        const prodId = `prod-sync-${sku.toLowerCase()}`;
        syncedProductIds.add(prodId);

        // Product Title from 07_Product_Details_Materials_*.txt or fallback
        const titleFromTxt = item.txtDetails?.title;
        const titleFromExcel = item.excelDetails?.name;
        const defaultTitle = item.subcategory && item.subcategory !== item.category
          ? `${item.category} — ${item.subcategory}`
          : item.category;
        const productName = titleFromTxt || titleFromExcel || defaultTitle;

        // Pricing
        const pricing = this.getDefaultPricing(item.category, productName);
        const basePrice = Number(item.excelDetails?.selling_price) || pricing.base;
        const mrp = Number(item.excelDetails?.mrp) || pricing.mrp;
        const discount = Math.round(((mrp - basePrice) / mrp) * 100);

        // Descriptions
        const fullDesc = item.txtDetails?.description || item.excelDetails?.description ||
          `Elevate your spaces with Creaftique's handcrafted ${productName}. Printed using high-fidelity archival pigment inks for true color vibrancy and longevity.`;
        const firstSentence = fullDesc.split('. ')[0] + '.';
        const shortDesc = firstSentence.length > 20 && firstSentence.length < 200
          ? firstSentence
          : `Handcrafted ${productName} customized to perfection with premium finishes.`;

        // Materials
        const material = item.txtDetails?.material || item.excelDetails?.material || 'Archival Substrate';

        const existing = db.getProductById(sku) || db.getProductById(prodId);

        const productPayload = {
          id: prodId,
          sku: sku,
          name: existing?.name || productName,
          category: item.category || 'Customized Products',
          category_slug: (item.category || 'customized-products').toLowerCase().replace(/\s+/g, '-'),
          subcategory: item.subcategory || item.category,
          subcategory_slug: (item.subcategory || item.category || '').toLowerCase().replace(/\s+/g, '-'),
          short_description: existing?.short_description || shortDesc,
          full_description: existing?.full_description || fullDesc,
          material: existing?.material || material,
          default_size: item.sizeOptions[0]?.name || 'Standard',
          base_price: basePrice,
          selling_price: basePrice,
          mrp: mrp,
          discount: discount > 0 ? discount : 40,
          tax: 18,
          stock: 250,
          production_time: pricing.production,
          tags: [item.category, item.subcategory, 'Creaftique', 'Custom Print', 'Bespoke'].filter(Boolean),
          keywords: [item.category.toLowerCase(), productName.toLowerCase(), sku.toLowerCase(), 'customized', 'photo print'],
          images: item.images,
          customization_available: true,
          requires_photo: true,
          required_photos_count: item.category.toLowerCase().includes('magnet') ? 6 : 1,
          custom_text_allowed: true,
          active: true,
          featured: existing ? existing.featured : (discovered.indexOf(item) < 6),
          costs: existing?.costs || {
            material_cost: Math.round(basePrice * 0.28),
            print_cost: Math.round(basePrice * 0.18),
            labor_cost: Math.round(basePrice * 0.12),
            packaging_cost: 60,
            shipping_cost: 80
          },
          custom_options: existing?.custom_options || {
            sizes: item.sizeOptions,
            materials: [
              { name: material, price_adj: 0, default: true },
              { name: 'Ultra-Gloss Luxe Surface', price_adj: 120 },
              { name: 'Museum Matte Velvet Finish', price_adj: 180 }
            ],
            finishes: [
              { name: 'Standard Satin Archival Protection', price_adj: 0, default: true },
              { name: 'Anti-Glare UV Seal Coat', price_adj: 90 },
              { name: 'Diamond Sparkle Holographic Coat', price_adj: 150 }
            ],
            frames: [
              { name: 'Frameless Standard Wrap / Bare', price_adj: 0, default: true },
              { name: 'Modern Matte Black Architectural Frame', price_adj: 350 },
              { name: 'Heritage Teak Wood Artisan Frame', price_adj: 450 },
              { name: 'Warm Champagne Gold Frame', price_adj: 490 }
            ],
            quantity_tiers: [
              { min: 1, max: 9, discount_percent: 0 },
              { min: 10, max: 49, discount_percent: 15 },
              { min: 50, max: 999, discount_percent: 30 }
            ],
            extras: [
              { id: 'express', name: 'Express 24h VIP Production', price_adj: 250 },
              { id: 'gift_wrap', name: 'Artisan Gift Box & Handwritten Card', price_adj: 150 }
            ]
          }
        };

        if (existing) {
          updatedCount++;
        } else {
          newCount++;
        }
        db.saveProduct(productPayload);
      }

      // Clean up any previously synced products that were deleted or removed from folder
      let removedCount = 0;
      const allCurrentProducts = db.getProducts();
      allCurrentProducts.forEach((p) => {
        if (p.id.startsWith('prod-sync-') && !syncedProductIds.has(p.id)) {
          db.deleteProduct(p.id);
          removedCount++;
        }
      });
      if (removedCount > 0) {
        console.log(`[CatalogSync] 🗑️ Removed ${removedCount} deleted products from database.`);
      }

      const syncResult = {
        connected: true,
        last_sync: new Date().toISOString(),
        products_found: discovered.length,
        new_products: newCount,
        updated_products: updatedCount,
        images_count: totalImages,
        source_dir: sourceDir,
        auto_watch_enabled: true
      };

      db.updateSettings({ sync_status: syncResult });
      db.logAudit({
        user: "Automatic Catalog Sync",
        action: "Synchronized Product Catalog",
        entity_type: "Catalog",
        entity_id: "All",
        new_value: `${discovered.length} products, ${totalImages} high-res images`
      });

      console.log(`[CatalogSync] ✅ SUCCESS! Synchronized ${discovered.length} products with ${totalImages} images.`);
      return { success: true, ...syncResult };
    } catch (err) {
      console.error('[CatalogSync] ❌ Error syncing catalog:', err);
      return { success: false, error: err.message };
    } finally {
      this.isScanning = false;
    }
  }

  /**
   * Automatic Real-Time Folder Watcher
   * Monitors the product folder on external drive or local disk.
   * When any folder or file is added/modified, it automatically re-syncs.
   */
  startAutoWatcher(customPath = null) {
    const targetPath = customPath || this.getSourcePath();
    if (!fs.existsSync(targetPath)) {
      console.warn(`[AutoWatcher] Target folder not accessible: ${targetPath}`);
      return;
    }

    if (this.watcher) {
      try {
        this.watcher.close();
      } catch {}
    }

    console.log(`[AutoWatcher] ⚡ Starting real-time watcher on: ${targetPath}`);
    try {
      this.watcher = fs.watch(targetPath, { recursive: true }, (eventType, filename) => {
        if (!filename) return;
        if (filename.startsWith('.') || filename.includes('.DS_Store') || filename.includes('Thumbs.db')) {
          return;
        }

        console.log(`[AutoWatcher] 🔔 Change detected in folder (${eventType}: ${filename}). Debouncing sync...`);
        clearTimeout(this.debounceTimer);
        this.debounceTimer = setTimeout(async () => {
          console.log(`[AutoWatcher] 🚀 Automatically updating website catalog from ${targetPath}...`);
          await this.syncCatalog(targetPath);
        }, 2500); // 2.5s debounce to let multi-file copy operations complete
      });
      console.log(`[AutoWatcher] ✅ Real-time automatic watcher is ACTIVE! Website will update automatically as you add folders.`);
    } catch (err) {
      console.warn(`[AutoWatcher] Notice on native watcher: ${err.message}. Enabling polling fallback.`);
      this.startPollingFallback(targetPath);
    }
  }

  startPollingFallback(targetPath, intervalMs = 15000) {
    setInterval(async () => {
      if (fs.existsSync(targetPath) && !this.isScanning) {
        await this.syncCatalog(targetPath);
      }
    }, intervalMs);
  }

  getSyncStatus() {
    const settings = db.getSettings();
    return settings.sync_status || {
      connected: false,
      last_sync: null,
      products_found: 0,
      new_products: 0,
      updated_products: 0,
      images_count: 0
    };
  }
}

module.exports = new CatalogSyncService();
